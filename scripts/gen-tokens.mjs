// Generates src/styles/tokens.css from design/tokens.md (+ moodboard :root for neutrals).
// tokens.md is the source of truth; values it defers to the moodboard are read from there.
// Run: npm run gen:tokens
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const md = fs.readFileSync(path.join(root, 'design/tokens.md'), 'utf8');
const mood = fs.readFileSync(path.join(root, 'design/Regi-moodboard.html'), 'utf8');

// Meaning colours: rows like  | `pink` | `#FF6FE7` | **Active** | ...
const meaning = {};
for (const m of md.matchAll(/\|\s*`([a-z-]+)`\s*\|\s*`(#[0-9A-Fa-f]{6})`\s*\|/g)) meaning[m[1]] = m[2].toUpperCase();
for (const k of ['pink', 'blue', 'yellow', 'white']) if (!meaning[k]) throw new Error(`tokens.md missing ${k}`);

// Neutrals tokens.md says to take "from moodboard": its :root block.
const rootBlock = /:root\s*{([^}]*)}/.exec(mood)[1];
const moodVars = Object.fromEntries([...rootBlock.matchAll(/--([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})/g)].map((m) => [m[1], m[2].toUpperCase()]));
const need = ['ink', 'ink-2', 'ink-3', 'grey-1', 'grey-2', 'grey-3', 'grey-4'];
for (const k of need) if (!moodVars[k]) throw new Error(`moodboard missing --${k}`);

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');

const css = `/* GENERATED by scripts/gen-tokens.mjs from design/tokens.md + design/Regi-moodboard.html.
   Do not edit by hand. This is the only file allowed to contain hex values or font names. */

:root {
  /* ── Meaning colours (tokens.md): colour = signal, never decoration ── */
  --pink: ${meaning.pink};     /* active */
  --blue: ${meaning.blue};     /* informational */
  --yellow: ${meaning.yellow};   /* sharing */
  --white: ${meaning.white};
  --white-rgb: ${rgb(meaning.white)};
  --pink-rgb: ${rgb(meaning.pink)};
  --blue-rgb: ${rgb(meaning.blue)};
  --yellow-rgb: ${rgb(meaning.yellow)};

  /* ── Ink + grey (moodboard :root) ── */
  --ink: ${moodVars.ink};
  --ink-rgb: ${rgb(moodVars.ink)};
  --ink-secondary: ${moodVars['ink-2']};
  --ink-tertiary: ${moodVars['ink-3']};
  --grey-1: ${moodVars['grey-1']};   /* step / chip fill */
  --grey-2: ${moodVars['grey-2']};   /* subtle fill, track */
  --grey-3: ${moodVars['grey-3']};   /* hairline borders */
  --grey-4: ${moodVars['grey-4']};   /* disabled, decorative only (fails text contrast) */
  --hairline: var(--grey-3);
  --surface: var(--white);
  --surface-glass: rgb(var(--white-rgb) / 0.96);
  --scrim: rgb(var(--ink-rgb) / 0.4);

  /* Tints: opacity variants of a meaning colour, never new hues */
  --pink-tint: rgb(var(--pink-rgb) / 0.1);      /* timer fill (~8–10%, B3.6) */
  --pink-tint-strong: rgb(var(--pink-rgb) / 0.18);
  --blue-tint: rgb(var(--blue-rgb) / 0.08);
  --yellow-tint: rgb(var(--yellow-rgb) / 0.35);
  --ink-tint: rgb(var(--ink-rgb) / 0.05);

  /* Text on a meaning colour. Pink and yellow fills take ink text: white on pink is 2.3:1 (fails WCAG). */
  --on-pink: var(--ink);
  --on-yellow: var(--ink);
  --on-blue: var(--white);
  --on-ink: var(--white);

  /* ── Type (tokens.md + moodboard scale, in rem) ── */
  --font-display: var(--font-spectral), 'Spectral', Georgia, serif;   /* italic 700 */
  --font-body: var(--font-instrument), 'Instrument Sans', system-ui, sans-serif;
  --text-display: 2.5rem;    /* 40 — moodboard Display */
  --text-title: 1.75rem;     /* 28 — screen titles, logo nav size */
  --text-subhead: 1.375rem;  /* 22 — moodboard Subheading */
  --text-number: 1.75rem;    /* 28 — moodboard stat-val */
  --text-headline: 1rem;     /* 16 — empty-state headline (B9.2) */
  --text-body: 0.875rem;     /* 14 */
  --text-body-sm: 0.8125rem; /* 13 */
  --text-label: 0.75rem;     /* 12 — UI label / secondary */
  --text-caption: 0.6875rem; /* 11 */
  --text-micro: 0.625rem;    /* 10 — tab labels, brand overlines */
  --weight-regular: 400;
  --weight-medium: 500;
  --weight-semibold: 600;
  --weight-display: 700;
  --tracking-label: 0.12em;
  --tracking-overline: 0.16em;
  --leading-tight: 1.15;
  --leading-body: 1.55;

  /* ── Spacing (tokens.md defaults) ── */
  --space-1: 4px;
  --space-2: 8px;
  --space-3: 14px;
  --space-4: 18px;
  --space-5: 24px;
  --space-6: 32px;
  --space-7: 44px;
  --gutter: 18px;

  /* ── Radius (moodboard: btn 4 · chip/step 10 · card 14 · sheet 20) ── */
  --radius-xs: 4px;
  --radius-sm: 8px;
  --radius-md: 10px;
  --radius-lg: 14px;
  --radius-xl: 20px;
  --radius-pill: 999px;

  /* ── Elevation (moodboard card) ── */
  --shadow-card: 0 1px 28px rgb(var(--ink-rgb) / 0.05);
  --shadow-sheet: 0 -8px 40px rgb(var(--ink-rgb) / 0.12);
  --shadow-raised: 0 4px 16px rgb(var(--ink-rgb) / 0.1);

  /* ── Layout ── */
  --app-max-width: 480px;
  --tabbar-height: 64px;
  --topbar-height: 52px;
  --tap-min: 44px;
  --focus-ring: 0 0 0 3px rgb(var(--blue-rgb) / 0.45);

  /* ── Motion ── */
  --ease-out: cubic-bezier(0.2, 0.8, 0.2, 1);
  --dur-fast: 150ms;
  --dur-med: 300ms;
}
`;

fs.writeFileSync(path.join(root, 'src/styles/tokens.css'), css);

// Same values for contexts that can't read CSS variables (PWA manifest, generated icons, OG images).
const ts = `// GENERATED by scripts/gen-tokens.mjs — do not edit. Prefer CSS variables; use this only where CSS can't reach.
export const color = {
  pink: '${meaning.pink}',
  blue: '${meaning.blue}',
  yellow: '${meaning.yellow}',
  white: '${meaning.white}',
  ink: '${moodVars.ink}',
  inkSecondary: '${moodVars['ink-2']}',
  inkTertiary: '${moodVars['ink-3']}',
  grey1: '${moodVars['grey-1']}',
  grey2: '${moodVars['grey-2']}',
  grey3: '${moodVars['grey-3']}',
} as const;
`;
fs.writeFileSync(path.join(root, 'src/styles/tokens.generated.ts'), ts);
console.log('wrote src/styles/tokens.css, src/styles/tokens.generated.ts');
